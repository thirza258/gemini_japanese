export const BUILDER_COURSES: KanjiCourse[] = LEVELS.flatMap((level) =>
  courseEntries[level].map(([id, title, description, characters]) => ({
    id: `${level}-${id}`,
    level,
    title,
    description,
    challengeIds: Array.from(
      characters,
      (character) => `${level}-build-${character}`,
    ),
  })),
);

export function getCourseChallenges(course: KanjiCourse): KanjiChallenge[] {
  return course.challengeIds.map((id) => {
    const challenge = KANJI_CHALLENGES.find((item) => item.id === id);
    if (!challenge)
      throw new Error(`Unknown challenge ${id} in course ${course.id}`);
    return challenge;
  });
}
